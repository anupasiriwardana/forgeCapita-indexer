// Generates abis/<Name>Abi.ts (`as const`) from the synced artifact JSON in abis/.
// The JSON files are the source of truth; never edit the generated .ts by hand.
//   node .claude/scripts/sync-abi.js indexer <ContractName> ...   (from the workspace root)
//   npm run abis
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const NAMES = [
  "ForgeCapitaFactory",
  "MilestoneEscrow",
  "ProjectToken",
  "DividendDistributor",
  "RevenueRouter",
  "P2PExchange",
  "ForgeCapitaRegistry",
];

const abisDir = join(dirname(fileURLToPath(import.meta.url)), "..", "abis");

for (const name of NAMES) {
  const artifact = JSON.parse(readFileSync(join(abisDir, `${name}.json`), "utf8"));
  if (!Array.isArray(artifact.abi)) throw new Error(`${name}.json has no abi array`);
  const body =
    `// GENERATED by scripts/generate-abis.mjs from ${name}.json. Do not edit.\n` +
    `export const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(join(abisDir, `${name}Abi.ts`), body);
  console.log(`generated abis/${name}Abi.ts`);
}
